export const CUSTOMER_STATUSES = ['ACTIVE', 'PENDING', 'BLOCKED'] as const;

export type CustomerStatus = (typeof CUSTOMER_STATUSES)[number];

/** The status pills of the dashboard: one of the statuses, or `ALL` for no filter. */
export type StatusFilter = CustomerStatus | 'ALL';

/** The pills, in the order they are shown. */
export const STATUS_FILTERS: readonly StatusFilter[] = ['ALL', 'ACTIVE', 'PENDING', 'BLOCKED'];

/** A customer as the API returns it. The snake_case keys are part of the contract. */
export interface Customer {
	id: string;
	name: string;
	email: string;
	status: CustomerStatus;
	/** ISO 8601 timestamp in UTC, generated by the server. */
	created_at: string;
}

export interface CreateCustomerInput {
	name: string;
	email: string;
}

export interface UpdateCustomerStatusInput {
	status: CustomerStatus;
}

/** One invalid field of a 422 response. */
export interface ValidationErrorDetail {
	field: string;
	message: string;
}

/** Body of every error response, shared by the backend and the mock. */
export interface ApiErrorBody {
	error: {
		code: string;
		message: string;
		request_id: string;
		details?: ValidationErrorDetail[];
	};
}

export const STATUS_LABELS: Record<CustomerStatus, string> = {
	ACTIVE: 'Activo',
	PENDING: 'Pendiente',
	BLOCKED: 'Bloqueado'
};

/** Labels of the filter pills, which are counted and so go in plural. */
export const STATUS_FILTER_LABELS: Record<StatusFilter, string> = {
	ALL: 'Todos',
	ACTIVE: 'Activos',
	PENDING: 'Pendientes',
	BLOCKED: 'Bloqueados'
};

export function isCustomerStatus(value: unknown): value is CustomerStatus {
	return CUSTOMER_STATUSES.some((status) => status === value);
}
